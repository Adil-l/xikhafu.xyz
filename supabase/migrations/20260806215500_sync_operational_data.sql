create or replace function public.load_public_app_bootstrap() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'users', coalesce((select jsonb_agg(jsonb_build_object(
      'id', u.user_id, 'name', u.user_name, 'avatar', u.avatar, 'active', u.active
    ) order by u.user_name) from public.app_users u), '[]'::jsonb),
    'settings', public.private_settings_json()
  );
$$;

create or replace function public.load_user_operational_state(p_user_id bigint, p_pin text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare result jsonb;
begin
  if public.private_check_user_pin(p_user_id, p_pin) <> 'ok' then return null; end if;
  select jsonb_build_object(
    'user', jsonb_build_object(
      'id', u.user_id, 'name', u.user_name, 'avatar', u.avatar, 'active', u.active,
      'monthlyBalance', u.monthly_balance, 'balanceResetAt', u.balance_reset_at,
      'updatedAt', u.updated_at
    ),
    'orders', coalesce((select jsonb_agg(public.private_order_json(o) order by o.ordered_at desc)
      from public.app_orders o where o.user_id = p_user_id), '[]'::jsonb),
    'recharges', coalesce((select jsonb_agg(public.private_recharge_json(r) order by r.created_at desc)
      from public.app_recharges r where r.user_id = p_user_id), '[]'::jsonb),
    'donations', coalesce((select jsonb_agg(public.private_donation_json(d) order by d.created_at desc)
      from public.app_donations d where d.user_id = p_user_id), '[]'::jsonb),
    'settings', public.private_settings_json()
  ) into result from public.app_users u where u.user_id = p_user_id;
  return result;
end;
$$;

create or replace function public.load_admin_operational_state(p_admin_pin text) returns jsonb
