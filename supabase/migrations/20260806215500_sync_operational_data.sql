alter table public.app_users
  add column if not exists monthly_balance numeric(12,2) not null default 0 check (monthly_balance >= 0),
  add column if not exists balance_reset_at timestamptz,
  add column if not exists active boolean not null default true;

alter table public.app_settings
  add column if not exists guest_ordering boolean not null default true,
  add column if not exists balance_policy text not null default 'allow-negative'
    check (balance_policy in ('block', 'allow-negative')),
  add column if not exists donation_day integer not null default 5 check (donation_day between 1 and 28),
  add column if not exists donation_goal text not null default 'o primeiro carro do padeiro (ou pelo menos um Yango 😅)';

create table public.app_orders (
  id bigint generated by default as identity primary key,
  sync_key text not null unique,
  order_type text not null check (order_type in ('user', 'guest')),
  user_id bigint references public.app_users(user_id),
  guest_name text,
  guest_phone text,
  ordered_at timestamptz not null default now(),
  status text not null default 'pending' check (status in ('pending', 'paid', 'debt', 'cancelled')),
  items jsonb not null default '[]'::jsonb check (jsonb_typeof(items) = 'array'),
  custom_request text not null default '',
  custom_price numeric(12,2) not null default 0 check (custom_price >= 0),
  needs_contact boolean not null default false,
  guest_donation numeric(12,2) not null default 0 check (guest_donation >= 0),
  updated_at timestamptz not null default now(),
  check ((order_type = 'user' and user_id is not null) or (order_type = 'guest' and user_id is null))
);

create table public.app_recharges (
  id bigint generated by default as identity primary key,
  sync_key text not null unique,
  user_id bigint not null references public.app_users(user_id),
  created_at timestamptz not null default now(),
  amount numeric(12,2) not null check (amount > 0),
  note text not null default 'Recarga',
  updated_at timestamptz not null default now()
);

create table public.app_donations (
  id bigint generated by default as identity primary key,
  sync_key text not null unique,
  order_sync_key text,
  user_id bigint references public.app_users(user_id),
  donor_name text not null default 'Convidado',
  amount numeric(12,2) not null check (amount > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.app_orders enable row level security;
alter table public.app_recharges enable row level security;
alter table public.app_donations enable row level security;
revoke all on public.app_orders from anon, authenticated;
revoke all on public.app_recharges from anon, authenticated;
revoke all on public.app_donations from anon, authenticated;

create index app_orders_user_id_idx on public.app_orders(user_id);
